package alerts

// ValidID permits sortable alert identifiers and their short prefixes, never
// paths, extensions, NTFS streams or special Windows path syntax.
func ValidID(id string) bool {
	if len(id) == 0 || len(id) > 128 {
		return false
	}
	for _, r := range id {
		if !((r >= '0' && r <= '9') || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || r == '-' || r == '_') {
			return false
		}
	}
	return true
}
